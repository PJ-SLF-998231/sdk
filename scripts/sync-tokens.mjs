#!/usr/bin/env node
// Copies Shelf's generated design tokens into src/styles/styles.css, rewriting
// the selectors so they apply under .shelf-sdk instead of the host page's
// :root. Usage: node scripts/sync-tokens.mjs [path/to/web/src/styles/tokens.css]
// (default: $SHELF_WEB_TOKENS, then ../shelf/web/src/styles/tokens.css).
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(process.argv[2] ?? process.env.SHELF_WEB_TOKENS ?? resolve(root, '../shelf/web/src/styles/tokens.css'));
const out = resolve(root, 'src/styles/styles.css');

let commit = 'unknown';
try {
  commit = execFileSync('git', ['-C', dirname(src), 'log', '-1', '--format=%H', '--', src], { encoding: 'utf8' }).trim() || commit;
} catch {
  /* not a git checkout */
}

let css = readFileSync(src, 'utf8');
// Drop the source's own header comment; ours replaces it.
css = css.replace(/^\s*\/\*[\s\S]*?\*\/\s*/, '');
css = css
  .replace(/:root:not\(\[data-theme\]\)/g, '.shelf-sdk:not([data-theme])')
  .replace(/:root,\s*\n\[data-theme="light"\]/g, '.shelf-sdk,\n.shelf-sdk[data-theme="light"]')
  .replace(/^\[data-theme="(\w+)"\]/gm, '.shelf-sdk[data-theme="$1"]');

if (/:root/.test(css.replace(/\/\*[\s\S]*?\*\//g, ''))) throw new Error('bare :root left after rewrite');

const header = `/*
 * GENERATED by scripts/sync-tokens.mjs. Do not edit by hand.
 * Source: web/src/styles/tokens.css in the Shelf repo, last changed in
 * commit ${commit}.
 * Selectors are scoped to .shelf-sdk so the host page is never restyled.
 * Theme: data-theme="light" | "dark" on .shelf-sdk; absent means follow the OS.
 */

`;
writeFileSync(out, header + css);
console.log(`wrote ${out} from ${src} (${commit})`);
